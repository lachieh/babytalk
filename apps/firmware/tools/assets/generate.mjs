async function fontFile(family, weight) {
  const file = path.join(cache, `${family.replaceAll(" ", "")}-${weight}.ttf`);
  if (existsSync(file)) return file;
  // Without a browser user agent, Google Fonts serves static TrueType instances per weight.
  const cssText = await (
    await fetch(
      `https://fonts.googleapis.com/css2?family=${family.replaceAll(" ", "+")}:wght@${weight}`
    )
  ).text();
  const url = cssText.match(/url\((https:[^)]+\.ttf)\)/)[1];
  writeFileSync(file, Buffer.from(await (await fetch(url)).arrayBuffer()));
  return file;
}

