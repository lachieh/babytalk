// Generates the firmware's brand assets from the web app, so the device and the web share one source:
//   - colour tokens: apps/web/src/app/globals.css (oklch) -> main/assets/tokens.h (RGB888)
//   - icons: apps/web/src/components/icon-paths.ts (24px stroke paths) -> A8 alpha images
//   - fonts: Plus Jakarta Sans and Instrument Serif (the web's fonts, OFL) -> LVGL bitmap fonts
// Outputs are committed. Run with `npm install && npm run generate` in this directory.
