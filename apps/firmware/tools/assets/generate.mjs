function oklchToHex(l, c, hDeg) {
  const h = (hDeg * Math.PI) / 180;
  const a = c * Math.cos(h);
  const b = c * Math.sin(h);
  const l_ = l + 0.396_337_777_4 * a + 0.215_803_757_3 * b;
  const m_ = l - 0.105_561_345_8 * a - 0.063_854_172_8 * b;
  const s_ = l - 0.089_484_177_5 * a - 1.291_485_548 * b;
  const [L, M, S] = [l_ ** 3, m_ ** 3, s_ ** 3];
  const lin = [
    4.076_741_662_1 * L - 3.307_711_591_3 * M + 0.230_969_929_2 * S,
    -1.268_438_004_6 * L + 2.609_757_401_1 * M - 0.341_319_396_5 * S,
    -0.004_196_086_3 * L - 0.703_418_614_7 * M + 1.707_614_701 * S,
  ];
  const gamma = (x) =>
    x <= 0.003_130_8 ? 12.92 * x : 1.055 * x ** (1 / 2.4) - 0.055;
  return lin
    .map((x) => Math.round(Math.min(1, Math.max(0, gamma(x))) * 255))
    .map((x) => x.toString(16).padStart(2, "0"))
    .join("");
}

function tokens(block) {
  const found = {};
  for (const m of block.matchAll(
    /--color-([a-z0-9-]+):\s*oklch\(([\d.]+)%\s+([\d.]+)\s+([\d.]+)\)/g
  )) {
    found[m[1]] = oklchToHex(Number(m[2]) / 100, Number(m[3]), Number(m[4]));
  }
  return found;
}

