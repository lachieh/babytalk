function a8Source(name, width, height, data) {
  const bytes = [];
  for (let i = 0; i < data.length; i++)
    bytes.push(`0x${data[i].toString(16).padStart(2, "0")}`);
  const rows = [];
  for (let i = 0; i < bytes.length; i += 24)
    rows.push(`    ${bytes.slice(i, i + 24).join(",")},`);
  return `static const uint8_t ${name}_map[] = {
${rows.join("\n")}
};

const lv_image_dsc_t ${name} = {
    .header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .w = ${width}, .h = ${height}, .stride = ${width}},
    .data_size = sizeof(${name}_map),
    .data = ${name}_map,
};
`;
}

async function alphaOf(svg, size) {
  const { data } = await sharp(Buffer.from(svg), { density: 72 * 8 })
    .resize(size, size)
    .ensureAlpha()
    .extractChannel("alpha")
    .raw()
    .toBuffer({ resolveWithObject: true });
  return data;
}

